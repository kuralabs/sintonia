"""
Command line: ``sintonia serve``, ``check``, ``health``, ``scan`` and
``import``.
"""

import argparse
import logging
import os
import sys
import time
from pathlib import Path

from . import __version__
from .checks import CheckError, preflight
from .config import ConfigError, load
from .scan import parse, to_channels, to_toml
from .scanner import DEFAULT_CHANNELS

DEFAULT_CONFIG = os.environ.get('SINTONIA_CONFIG', '/config/config.toml')

log = logging.getLogger('sintonia')


def _setup_logging(verbose):
    """
    :param bool verbose: Log debug messages.
    """
    logging.basicConfig(
        level=logging.DEBUG if verbose else logging.INFO,
        format='%(asctime)s %(levelname)s %(name)s: %(message)s',
    )
    # One line per MediaMTX API poll is noise.
    logging.getLogger('httpx2').setLevel(logging.WARNING)


def _load_checked(path):
    """
    Load the configuration and run the start-up checks.

    :param str path: Configuration file.

    :return: The configuration and the adapters to use.
    :rtype: tuple

    :raises SystemExit: With a message if anything is wrong.
    """
    try:
        config = load(path)
        adapters = preflight(config)
    except (ConfigError, CheckError) as e:
        log.error('%s', e)
        raise SystemExit(1) from e
    return config, adapters


def serve(args):
    import uvicorn

    from .app import create_app

    config, adapters = _load_checked(args.config)
    log.info(
        'sintonia %s: %d channels, tuners %s, %s transcoding',
        __version__, len(config.channels),
        ', '.join(map(str, adapters)), config.transcode.hwaccel,
    )
    uvicorn.run(
        create_app(config, adapters),
        host=config.server.host,
        port=config.server.port,
        log_config=None,
        access_log=args.verbose,
    )


def check(args):
    config, adapters = _load_checked(args.config)
    print(
        f'ok: {len(config.channels)} channels, tuners '
        f'{", ".join(map(str, adapters))}, '
        f'{config.transcode.hwaccel} transcoding works'
    )


def health(args):
    import urllib.request

    try:
        port = load(args.config).server.port
        url = f'http://127.0.0.1:{port}/healthz'
        with urllib.request.urlopen(url, timeout=5) as response:
            ok = response.status == 200
    except (ConfigError, OSError):
        ok = False
    raise SystemExit(0 if ok else 1)


def scan(args):
    from . import scanner
    from .dvb import find_adapters

    try:
        channels = scanner.parse_channels(args.channels)
    except ValueError as e:
        log.error('%s', e)
        raise SystemExit(2) from e
    if args.adapters:
        adapters = [int(a) for a in args.adapters.split(',')]
    else:
        adapters = find_adapters()
    if not adapters:
        log.error('no DVB adapters found in /dev/dvb')
        raise SystemExit(1)

    def progress(result):
        multiplex = result['multiplex']
        if not result['locked']:
            log.debug('%s: no signal', scanner.band(result['channel']))
        elif multiplex is None or multiplex.services is None:
            log.info('%s: locked, but no service list (signal too weak)',
                     scanner.describe(result))
        else:
            names = ', '.join(s['name'] for s in multiplex.services.values())
            log.info('%s: %s', scanner.describe(result), names)

    log.info('scanning %d RF channels on tuners %s', len(channels),
             ', '.join(map(str, adapters)))
    started = time.monotonic()
    try:
        results = scanner.scan(
            adapters, channels, lock_timeout=args.lock_timeout,
            tables_timeout=args.tables_timeout, progress=progress,
        )
    except scanner.ScanError as e:
        log.error('%s', e)
        raise SystemExit(1) from e
    found = scanner.to_channels(results, include_oneseg=args.oneseg)
    log.info('found %d channels in %.0f s', len(found),
             time.monotonic() - started)
    if not found:
        raise SystemExit(1)
    header = (
        f'Generated by "sintonia scan" on {time.strftime("%Y-%m-%d")}.',
        'Numbers follow the TV convention: the major number is announced',
        'by the broadcaster. The list order is the Up/Down order. Channels',
        'marked weak may stutter or fail to start.',
    )
    sys.stdout.write(to_toml(found, header=header))


def import_(args):
    text = Path(args.file).read_text()
    channels = to_channels(parse(text), include_oneseg=args.oneseg)
    if not channels:
        log.error('no services found in %s', args.file)
        raise SystemExit(1)
    sys.stdout.write(to_toml(channels))


def main(argv=None):
    """
    Entry point.

    :param list argv: Arguments, without the program name.
    """
    parser = argparse.ArgumentParser(
        prog='sintonia',
        description='Simple web app for live over-the-air TV.',
    )
    parser.add_argument(
        '--version', action='version', version=f'%(prog)s {__version__}',
    )
    parser.add_argument('-v', '--verbose', action='store_true')
    commands = parser.add_subparsers(dest='command', required=True)

    for name, function, text in (
        ('serve', serve, 'run the server'),
        ('check', check, 'validate the configuration and the hardware'),
        ('health', health, 'exit 0 if the local server is healthy'),
    ):
        sub = commands.add_parser(name, help=text)
        sub.add_argument(
            '-c', '--config', default=DEFAULT_CONFIG,
            help=f'configuration file (default: {DEFAULT_CONFIG})',
        )
        sub.set_defaults(function=function)

    sub = commands.add_parser(
        'scan', help='scan for channels with the tuners, print [[channels]]',
        description='Scan for channels and print [[channels]] tables. '
        'Progress is logged to stderr; redirect stdout to a file. The '
        'tuners must be free: stop the server first.',
    )
    sub.add_argument(
        '--channels', default=DEFAULT_CHANNELS,
        help='RF channels to scan, such as 14-51 or 18,22,38 '
        '(default: %(default)s, VHF-high and UHF)',
    )
    sub.add_argument(
        '--adapters',
        help='comma separated adapter numbers (default: all)',
    )
    sub.add_argument(
        '--lock-timeout', type=float, default=5.0, metavar='SECONDS',
        help='time to wait for a signal lock (default: %(default)s)',
    )
    sub.add_argument(
        '--tables-timeout', type=float, default=12.0, metavar='SECONDS',
        help='time to wait for the service tables (default: %(default)s)',
    )
    sub.add_argument(
        '--oneseg', action='store_true',
        help='include one-seg (mobile, low resolution) services',
    )
    sub.set_defaults(function=scan)

    sub = commands.add_parser(
        'import', help='convert a dvbv5-scan channel file to [[channels]]',
    )
    sub.add_argument('file', help='dvbv5-scan output file')
    sub.add_argument(
        '--oneseg', action='store_true',
        help='include one-seg (mobile, low resolution) services',
    )
    sub.set_defaults(function=import_)

    args = parser.parse_args(argv)
    _setup_logging(args.verbose)
    args.function(args)


if __name__ == '__main__':
    main()
